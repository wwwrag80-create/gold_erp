def build(out, silent):
    out.mkdir(parents=True, exist_ok=True)
    topics, shots = [], []
    for topic, sid, title, sub, say, opt in STEPS:
        if not topics or topics[-1] != topic:
            topics.append(topic)
            shots.append({"type": "chapter", "n": len(topics), "title": topic, "desc": ""})
        s = dict(by_id[sid])
        src = SRC / s["file"]
        if opt.get("id"):                       # اللقطة نفسها بإبرازٍ آخر — باسمٍ آخر
            s["file"] = opt["id"] + ".png"
        link = out / s["file"]
        if not link.exists():
            os.symlink(src, link)
        for k in ("tap", "press", "focus"):
            if k in opt:
                s[k] = opt[k]
        s.update({"title": title, "chapter": len(topics)})
        if silent:
            s.pop("say", None)
            s["sub"] = sub
        else:
            s["say"] = say
        shots.append(s)
    meta = {
        "short": True, "silent": silent, "bpm": 96, "benefits": BENEFITS,
        "introSub": "دليل المندوب — بسرعة ووضوح" if silent else "دليل المندوب في دقيقتين",
        "introChip": "تطبيق أندرويد · مجاني",
        "outroTitle": "ابدأ الآن",
        "outroLines": ["أضف المصنع وعملاءك", "سجّل البضاعة، وبِع من الأطقم التي معك", "حصّل وسدّد، وأرسل الكشف صورةً"],
    }
    if not silent:
        meta["intro"] = "هَذَا هُوَ تَطْبِيقُ حِسَابَاتِ الذَّهَبِ. هَيَّا نَبْدَأْ!"
        meta["outro"] = "سَهْلٌ، وَوَاضِحٌ. اِبْدَأِ الْآنَ!"
    (out / "manifest.json").write_text(json.dumps({"viewport": full["viewport"], "meta": meta, "shots": shots},
                                                  ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"✔ {out} — {sum(1 for x in shots if x['type'] == 'shot')} خطوة")


build(OUT_SILENT, True)
build(OUT_VOICE, False)
