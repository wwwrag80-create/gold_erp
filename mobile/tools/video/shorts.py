# خطواتٌ تُترك في النسخة المسموعة (شُرحت قبلها بالصوت) — لتبقى في دقيقةٍ ونصف
VOICE_SKIP = {"52_sale_save"}


def build(out, silent):
    out.mkdir(parents=True, exist_ok=True)
    topics, shots = [], []
    for topic, sid, title, sub, say in STEPS:
        if not silent and sid in VOICE_SKIP:
            continue
        if not topics or topics[-1] != topic:
            topics.append(topic)
            shots.append({"type": "chapter", "n": len(topics), "title": topic, "desc": ""})
        s = dict(by_id[sid])
        link = out / s["file"]
        if not link.exists():
            os.symlink(SRC / s["file"], link)
        s.update({"title": title, "chapter": len(topics)})
        if silent:
            s.pop("say", None)
            s["sub"] = sub
        else:
            s["say"] = say
        shots.append(s)
    meta = {
        "short": True, "silent": silent, "bpm": 100,
        "introSub": "دليل المندوب في دقيقة" if silent else "دليل المندوب في دقيقةٍ ونصف",
        "introChip": "تطبيق أندرويد · مجاني",
        "outroTitle": "ابدأ الآن",
        "outroLines": ["أضف المصنع وعملاءك", "سجّل البضاعة، وبِع من الأطقم التي معك", "حصّل وسدّد، وأرسل الكشف صورةً"],
    }
    if not silent:
        meta["intro"] = "حِسَابَاتُكَ مَعَ الْعُمَلَاءِ وَالْمَصَانِعِ، كُلُّهَا فِي جَوَّالِكَ. هَيَّا نَبْدَأْ!"
        meta["outro"] = "حِسَابَاتُكَ وَاضِحَةٌ، وَمَحْفُوظَةٌ. اِبْدَأِ الْآنَ!"
    (out / "manifest.json").write_text(json.dumps({"viewport": full["viewport"], "meta": meta, "shots": shots},
                                                  ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"✔ {out} — {sum(1 for x in shots if x['type'] == 'shot')} خطوة")


build(OUT_SILENT, True)
build(OUT_VOICE, False)
