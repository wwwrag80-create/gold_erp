# -*- coding: utf-8 -*-
"""نظام التصميم (5.1) — المقاسات والمسافات والخطوط، **لا الألوان**.

الألوان في `ui.theme` كما هي منذ سنة ولا تُمسّ: هوية جاديت (الذهب المعتّق
على الأسطح الدافئة) ولوحتا الفاتح والليلي. وهذا الملف يكمّلها بما كان
متفرّقاً أرقاماً في مواضعها: حجمُ عنوانٍ هنا 19 وهناك 17، وزاويةٌ 10
وأخرى 8 وثالثة 12، وحشوٌ لكل زرٍّ على هواه — فتبدو الشاشات وكأن كلاً منها
صُمّم وحده.

هنا **سلّمٌ واحد** لكل شيء، يُكتب في ورقة الأنماط بأسماء رمزية كالألوان
(`@rCard` · `@fsTitle` · `@hCtl`)، فيُعدَّل من موضعٍ واحد ويتبعه النظام كله:

  · الخط: سلّمٌ من تسع درجات بأوزانٍ مدروسة — العنوان كبيرٌ عريض، والحقل
    واضح، والثانوي أصغر بدرجةٍ لا باهت، والرقم المهم عريضٌ عالي التباين.
  · المسافات: مضاعفات 4 (4 · 8 · 12 · 16 · 20 · 24 · 32).
  · الزوايا: 6 للحقول والأزرار والعناصر الصغيرة · 12 للبطاقات والجداول ·
    14 للنوافذ.
  · الارتفاعات: 36 للحقل والزر (34 المدمج · 42 الكبير).

ومقاس الخط يمرّ بمعامل المستخدم وتناسب الشاشة في `ui.theme.build`
كما كان — فكل ما هنا بمقاس «عادي» على شاشة 1920.
"""

# ── المسافات ─────────────────────────────────────────────────────────
SPACE = {"xxs": 2, "xs": 4, "sm": 8, "md": 12, "lg": 16, "xl": 20,
         "xxl": 24, "xxxl": 32}

# ── الزوايا ──────────────────────────────────────────────────────────
RADIUS = {"xs": 4, "sm": 6, "ctl": 6, "card": 12, "dlg": 14, "pill": 999}

# ── الارتفاعات ───────────────────────────────────────────────────────
HEIGHT = {"ctlSm": 30, "ctl": 36, "ctlLg": 42, "row": 40, "hdr": 40,
          "bar": 52}

# ── سلّم الخط (بكسل عند المقاس العادي) ─────────────────────────────
# الأسماء وظيفية: ما يُكتب به العنوان لا «22 بكسل» — فيبقى المعنى صحيحاً
# إن تغيّر المقاس.
TYPE = {
    "display": 30,    # اسم المصنع في الواجهة الرئيسية
    "title": 21,      # عنوان الشاشة
    "h2": 17,         # عنوان قسمٍ داخل الشاشة / بطاقة
    "h3": 15,         # عنوان مجموعة حقول · رأس الجدول
    "body": 16,       # نصّ النظام والحقول
    "table": 16,      # خانات الجداول
    "label": 14,      # تسمية حقل · عنوان بطاقة رقم
    "caption": 13,    # شرحٌ ثانوي · تاريخ · وحدة
    "micro": 12,      # تلميحٌ تحت عنصر · عدّاد
    "kpi": 26,        # رقمٌ رئيسي في بطاقة
    "kpiSm": 21,      # رقمٌ في لوحةٍ مدمجة
}

# أوزان IBM Plex Sans Arabic المرفقة: 400 · 500 · 600 · 700. محلّل أنماط
# Qt يقسم الوزن على 8 (500 ← 62 شبه عريض، 600 ← 75 عريض) — فالأسماء هنا
# بما **يُرى** لا بالرقم الخام.
WEIGHT = {"regular": "normal", "medium": "500", "strong": "bold"}


def tokens():
    """الأسماء الرمزية لورقة الأنماط: `@sp_md` · `@rCard` · `@fsTitle` …

    تُدمج مع ألوان المظهر في `ui.theme.build`، والألوان تغلب عند تشابه
    الاسم (لا تشابه، لكنها الضمانة: هذا الملف لا يغيّر لوناً أبداً)."""
    out = {}
    for k, v in SPACE.items():
        out[f"sp_{k}"] = f"{v}px"
    for k, v in RADIUS.items():
        out["r" + k[0].upper() + k[1:]] = f"{v}px"
    for k, v in HEIGHT.items():
        out["h" + k[0].upper() + k[1:]] = f"{v}px"
    for k, v in TYPE.items():
        out["fs" + k[0].upper() + k[1:]] = f"{v}px"
    for k, v in WEIGHT.items():
        out["fw" + k[0].upper() + k[1:]] = v
    return out


def px(name, scale=1.0):
    """مقاسٌ من السلّم بعد معامل الواجهة — للمكوّنات المرسومة في الشيفرة."""
    v = TYPE.get(name) or SPACE.get(name) or HEIGHT.get(name) or \
        RADIUS.get(name) or 0
    return max(1, int(round(float(v) * float(scale or 1.0))))
